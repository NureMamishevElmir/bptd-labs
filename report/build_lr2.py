    "«піднесення до квадрата й множення»: показник переглядається від молодшого біта до старшого, основа щоразу "
    "підноситься до квадрата, а якщо біт дорівнює 1, результат множиться на основу. Так потрібно лише близько "
    "2·log2(E) множень замість E. У роботі використано «підручникову» схему RSA без доповнення; у реальних "
