r.h2("4.3.2 Параметри алгоритму")
r.p("Загальновідомі параметри – просте число Q і первісний корінь A. A є первісним коренем Q, якщо його степені "
    "A^1, A^2, …, A^(Q−1) mod Q дають усі числа від 1 до Q − 1. Програма підтримує два набори параметрів:")
r.bullets([
    "навчальний: Q = 23, A = 5. Первісність перевіряється прямим перебором степенів: 5^k mod 23 для k = 1…22 "
    "дає всі 22 різні значення, а 2 первісним коренем не є – його степені повторюються вже після 11 кроків;",
    "надійний: 2048-бітне просте число з RFC 3526 (група 14). Воно «безпечне»: Q = 2q + 1, де q теж просте. Для "
    "такого Q число A є первісним коренем тоді й лише тоді, коли A^2 ≠ 1 і A^q ≠ 1 (mod Q). Програма шукає "
    "найменший такий A – ним виявилось A = 11 (стандартне значення 2 не підходить, бо 2^q mod Q = 1).",
])

r.h2("4.3.3 Обмін ключами")
r.p("Кожен користувач обирає випадкове секретне число X (2 ≤ X < Q − 1, генератор crypto.getRandomValues у "
    "браузері) і обчислює відкритий ключ Y = A^X mod Q власною функцією піднесення до квадрата й множення. "
    "Сервер отримує й пересилає лише значення Y. Для кожної пари учасників i, j обидві сторони обчислюють спільний "
    "ключ:")
r.formula("K = (Yj)^Xi mod Q = (Yi)^Xj mod Q = A^(Xi·Xj) mod Q.")
r.p("Щоб отримати ключ симетричного шифру, від K береться SHA-256, і результат використовується як 256-бітний ключ "
    "AES-GCM. Перші 8 hex-цифр SHA-256(K) показуються як «відбиток» ключа: якщо в обох учасників відбитки "
    "однакові, ключі узгоджено правильно.")

r.h2("4.3.4 Чат для трьох і більше користувачів")
